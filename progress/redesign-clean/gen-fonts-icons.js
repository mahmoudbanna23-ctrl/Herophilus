const fs = require('fs');
const path = require('path');
const V = 'D:/scratch 2026/clean-vendor';
const APP = 'D:/claude os/Medical school/Herophilus-redesign/app';

// ---- fonts ----
const b64 = f => fs.readFileSync(path.join(V, 'fonts', f)).toString('base64');
const faces = [
  ['Geist', 'normal', '100 900', 'Geist-Variable.woff2'],
  ['Newsreader', 'normal', '200 800', 'newsreader-latin-opsz-normal.woff2'],
  ['Newsreader', 'italic', '200 800', 'newsreader-latin-opsz-italic.woff2'],
];
let css = '/* Geist (UI) and Newsreader (titles, reading): both SIL OFL 1.1, embedded unmodified as base64.\n' +
  '   Why base64: over file:// Chrome blocks url() font loads as CORS errors. Licences: assets/licences/.\n' +
  '   Geist wght 100-900. Newsreader wght 200-800 plus opsz 6-72 (font-optical-sizing:auto picks the cut).\n' +
  '   Generated by progress/redesign-clean/gen-fonts-icons.js; edit that, not this file. */\n';
for (const [fam, style, wght, file] of faces) {
  css += "@font-face{font-family:'" + fam + "';font-style:" + style + ';font-weight:' + wght +
    ';font-display:block;src:url(data:font/woff2;base64,' + b64(file) + ") format('woff2')}\n";
}
fs.writeFileSync(path.join(APP, 'css/fonts-ui.css'), css);

// ---- licences ----
const lic = path.join(APP, 'assets/licences');
fs.mkdirSync(lic, { recursive: true });
fs.copyFileSync(path.join(V, 'fonts/Geist-LICENSE.txt'), path.join(lic, 'Geist-LICENSE.txt'));
fs.copyFileSync(path.join(V, 'fonts/Newsreader-LICENSE.txt'), path.join(lic, 'Newsreader-LICENSE.txt'));
fs.copyFileSync(path.join(V, 'tabler-outline-LICENSE.txt'), path.join(lic, 'tabler-outline-LICENSE.txt'));
fs.copyFileSync(path.join(V, 'open-props/LICENSE'), path.join(lic, 'open-props-LICENSE.txt'));

// ---- icons ----
const names = ['x', 'list', 'flag', 'clock', 'arrow-left', 'arrow-right', 'rotate', 'rotate-clockwise', 'home',
  'check', 'notes', 'pencil', 'chevron-left', 'chevron-right', 'chevron-down', 'chevron-up', 'alert-triangle'];
let out = '/* Tabler outline icons (MIT, assets/licences/tabler-outline-LICENSE.txt), 24x24, 2px stroke, currentColor.\n' +
  '   Separate from icons.js (frozen). uiIco(name,size) returns an inline <svg>. Generated by\n' +
  '   progress/redesign-clean/gen-fonts-icons.js. */\nvar UI_ICONS={\n';
names.forEach((n, i) => {
  const svg = fs.readFileSync(path.join(V, 'tabler-outline', n + '.svg'), 'utf8');
  const paths = [...svg.matchAll(/<path\s+d="([^"]+)"\s*\/>/g)].map(m => m[1]); // skips the empty stroke="none" path
  const inner = paths.map(d => '<path d="' + d + '"/>').join('');
  out += "  '" + n + "':'" + inner + "'" + (i < names.length - 1 ? ',' : '') + '\n';
});
out += '};\n' +
  'function uiIco(name,size){\n' +
  '  var s=size||18, body=UI_ICONS[name]||"";\n' +
  '  return \'<svg class="ui-ico" viewBox="0 0 24 24" width="\'+s+\'" height="\'+s+\'" fill="none" stroke="currentColor" \'+\n' +
  '    \'stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">\'+body+\'</svg>\';\n' +
  '}\n';
fs.writeFileSync(path.join(APP, 'js/ui-icons.js'), out);
console.log('ok', css.length, out.length);
