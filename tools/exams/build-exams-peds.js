/* Build the Pediatrics endpoint model-final-exam views without moving
   questions out of their topic chapters.  Exam membership is the entry id
   (pedep-mf1..4 = Endpoint part 1, pedep2-mf1..4 = Endpoint part 2); printed
   order is the page in each entry's source, then the number in the id.
   Folded ids (app/data/folds.js) are replaced by their kept id and a repeat
   inside one exam is dropped. */
const fs=require('fs');
const path=require('path');
const vm=require('vm');

const root=path.resolve(__dirname,'..','..');
const data=path.join(root,'app','data');
const box={};
vm.createContext(box);
['questions.peds.js','questions.peds.ep.js','questions.peds.ep2.js','questions.peds.sa.js','folds.js']
  .forEach(f=>vm.runInContext(fs.readFileSync(path.join(data,f),'utf8'),box,{filename:f}));
const all=[].concat(box.Q_PEDS,box.Q_PEDS_EP,box.Q_PEDS_EP2,box.Q_PEDS_SA);
const folded=box.FOLDED||{};

const examIds=[];
['pedep','pedep2'].forEach(p=>[1,2,3,4].forEach(n=>examIds.push(p+'-mf'+n)));
const exams={};
examIds.forEach(ex=>{
  const mine=all.filter(q=>q.id.indexOf(ex+'-')===0).map(q=>{
    const pg=/\.pdf\s+p\.(\d+)/i.exec(q.source||'');
    return {id:q.id,page:pg?Number(pg[1]):Infinity,n:Number(q.id.slice(ex.length+1))};
  });
  mine.sort((a,b)=>a.page-b.page||a.n-b.n);
  const seen=new Set(); const ids=[];
  mine.forEach(r=>{
    const id=folded[r.id]||r.id;
    if(seen.has(id))return;
    seen.add(id); ids.push(id);
  });
  exams[ex]=ids;
  console.log(ex+': '+ids.length+(mine.some(r=>r.page===Infinity)?' (some entries have no page)':''));
});
fs.writeFileSync(path.join(data,'exams.peds.js'),
  '/* Generated by tools/exams/build-exams-peds.js; topical homes stay in the Pediatrics arrays. */\n'+
  'var EXAMS_PEDS = '+JSON.stringify(exams,null,2)+';\n');
