/* Build the endpoint model-final-exam views without moving questions out of
   their topic chapters.  Sources are the durable fold record; pairs.json gives
   the physical-page order where the book repeats a printed number. */
const fs=require('fs');
const path=require('path');
const vm=require('vm');

const root=path.resolve(__dirname,'..','..');
const data=path.join(root,'app','data');
const box={};
vm.createContext(box);
vm.runInContext(fs.readFileSync(path.join(data,'questions.neuro.js'),'utf8'),box,
  {filename:'questions.neuro.js'});
const sizes=[65,64,64,71,43,45];
const exams={};

function mentions(q,n){
  const re=new RegExp('Model Final Exam\\s+'+n+'\\s*,\\s*(Q\\d+|unnumbered question)', 'gi');
  const out=[]; let m;
  while((m=re.exec(q.source||''))){
    const tail=(q.source||'').slice(m.index,m.index+180);
    const page=/p\.(\d+)/i.exec(tail);
    out.push({label:m[1],page:page?Number(page[1]):Infinity});
  }
  /* A few fold notes shorten a second printing to "also at Q..." or
     "again unnumbered ... same exam" after naming the exam once. */
  const named=new RegExp('Model Final Exam\\s+'+n+'\\b','gi');
  while((m=named.exec(q.source||''))){
    const next=/Model Final Exam\s+\d+\b/gi;
    next.lastIndex=named.lastIndex;
    const after=next.exec(q.source||'');
    const section=(q.source||'').slice(m.index,after?after.index:undefined);
    const extra=/also at (Q\d+)\s*,\s*p\.(\d+)|again unnumbered[^.]*p\.(\d+)/gi;
    let more;
    while((more=extra.exec(section))){
      out.push({label:more[1]||'unnumbered question',page:Number(more[2]||more[3])});
    }
  }
  return out;
}

for(let n=1;n<=6;n++){
  const pairs=JSON.parse(fs.readFileSync(path.join(root,'content','neuro','qb-pages','_ep-work','fe'+n,'pairs.json'),'utf8'));
  const byPage=new Map(pairs.map(x=>[x.q,x]));
  const rows=[];
  box.Q_NEURO.forEach(q=>mentions(q,n).forEach(hit=>{
    const slot=byPage.get(hit.page);
    rows.push({id:q.id,label:hit.label,page:hit.page,slot:slot?slot.pk:null});
  }));
  rows.sort((a,b)=>a.page-b.page||a.id.localeCompare(b.id));
  const ids=[]; const used=new Set(); const placedPages=new Set();
  rows.forEach(row=>{
    if(used.has(row.id))return;
    used.add(row.id); ids.push(row.id); placedPages.add(row.page);
  });
  const missing=pairs.filter(x=>!placedPages.has(x.q)).map(x=>
    n===4&&x.q===2002?'unnumbered (p.2002)':'Q'+x.n);
  exams['np-fe'+n]=ids;
  console.log('np-fe'+n+': '+ids.length+'/'+sizes[n-1]+' found; unplaced: '+(missing.length?missing.join(', '):'none'));
}
fs.writeFileSync(path.join(data,'exams.neuro.js'),
  '/* Generated by tools/exams/build-exams-neuro.js; topical homes stay in Q_NEURO. */\n'+
  'var EXAMS_NEURO = '+JSON.stringify(exams,null,2)+';\n');
