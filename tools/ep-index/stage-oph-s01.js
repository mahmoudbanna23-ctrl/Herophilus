'use strict';

// Generate an OCR-backed staging array for paired endpoint questions.
// Usage:
//   node tools/ep-index/stage-oph-s01.js <pdf> <ocr-dir> <first-unmarked> <last-marked> <out> <staged-var>
//
// The arguments describe adjacent unmarked/marked pairs: first-unmarked must be
// odd, last-marked must be even, and each source page is followed by its marked
// page.  `key` is written as a 0-based index into `opts`, or null when keypos
// abstains.  keypos is an unconfirmed measurement, never page-image confirmation.

const childProcess = require('child_process');
const fs = require('fs');
const path = require('path');

function die(message) {
  console.error('stage-oph-s01: ' + message);
  process.exit(2);
}

function usage() {
  die('usage: node stage-oph-s01.js <pdf> <ocr-dir> <first-unmarked> <last-marked> <out> <staged-var>');
}

function js(value) {
  return JSON.stringify(value);
}

function compact(lines) {
  return lines.map(line => line.trim()).filter(Boolean).join(' ').replace(/\s+/g, ' ').trim();
}

function parsePass(text, page, n) {
  const lines = text.replace(/\r/g, '').split('\n').map(line => line.trim());
  while (lines.length && !lines[lines.length - 1]) lines.pop();
  if (lines[lines.length - 1] === String(page)) lines.pop();

  const stemLines = [];
  const opts = [];
  let current = -1;
  for (const line of lines) {
    const m = /^([A-Da-d])[.,)]\s*(.*)$/.exec(line);
    if (m) {
      const index = m[1].toUpperCase().charCodeAt(0) - 65;
      if (index !== opts.length) return null;
      opts.push(m[2]);
      current = index;
    } else if (current < 0) {
      stemLines.push(line);
    } else {
      opts[current] += ' ' + line;
    }
  }
  if (opts.length !== 4) return null;

  let stem = compact(stemLines);
  // OCR has read the first two numbers as I./I O./I l. on this book.  The
  // sequential staging n, rather than that printed token, identifies the entry.
  stem = stem.replace(/^(?:\d+|[Il]\s*[IlO]?)\.\s*/, '');
  return { stem, opts: opts.map(option => compact([option])) };
}

function parseQuestion(ocrDir, page, n) {
  const file = path.join(ocrDir, 'p' + String(page).padStart(4, '0') + '.txt');
  const parts = fs.readFileSync(file, 'utf8').split(/\r?\n--- 150dpi ---\r?\n/);
  const candidates = parts.map(part => parsePass(part, page, n)).filter(Boolean);
  if (!candidates.length) die('p.' + page + ': neither OCR pass produced four A-D options');
  candidates.sort((a, b) => (b.stem.length + b.opts.join('').length) - (a.stem.length + a.opts.join('').length));
  return candidates[0];
}

function measureKey(pdf, page, optionCount) {
  const raw = childProcess.execFileSync('python', [
    path.join(__dirname, 'keypos.py'), pdf, String(page), String(optionCount)
  ], { encoding: 'utf8' });
  const result = JSON.parse(raw);
  return {
    keyIndex: result.key_index,
    reason: result.reason,
    yellowPx: result.yellow_px,
    highlightPx: result.highlight_px,
    bodyBands: result.body_bands,
    litBands: result.lit_bands ? result.lit_bands.length : 0,
    bandsBelowHighlight: result.bands_below_highlight
  };
}

function hasDigits(question) {
  return /\d/.test(question.stem) || question.opts.some(option => /\d/.test(option));
}

function render(rows, svar, first, last) {
  const out = [
    '/* OCR-backed staging record. Generated by tools/ep-index/stage-oph-s01.js.',
    '   Source pairs: unmarked p.' + first + ' through marked p.' + last + '.',
    '   `key` is stored 0-based as an index into `opts`; null means keypos.py abstained.',
    '   Every keypos value is unconfirmed against the page image. `expl` is empty because',
    '   this OCR staging pass is limited to stems and options, not explanation transcription. */',
    '',
    'var ' + svar + ' = [',
    ''
  ];
  for (const row of rows) {
    const note = [
      'KEY: keypos.py -> ' + (row.key === null ? 'null' : row.key) + ' (' + row.keypos.reason + '); UNCONFIRMED AGAINST PAGE IMAGE.'
    ];
    if (row.numberCheck) note.push('NUMBER CHECK: stem/options contain digits; check numbers, units, exponents and doses against the page image.');
    out.push('{ n:' + row.n + ', p:' + row.p + ', key:' + (row.key === null ? 'null' : row.key) + ',');
    out.push('  stem:' + js(row.stem) + ',');
    out.push('  opts:' + js(row.opts) + ',');
    out.push('  expl:"",');
    out.push('  keySource:"keypos.py; unconfirmed against page image",');
    out.push('  keypos:' + js(row.keypos) + ',');
    out.push('  numberCheck:' + row.numberCheck + ',');
    out.push('  note:' + js(note.join(' ')) + ' },');
    out.push('');
  }
  out.push('];', '');
  return out.join('\n');
}

function main(args) {
  if (args.length !== 6) usage();
  const [pdf, ocrDir, firstArg, lastArg, outFile, svar] = args;
  const first = Number(firstArg), last = Number(lastArg);
  if (!Number.isSafeInteger(first) || !Number.isSafeInteger(last) || first % 2 !== 1 || last % 2 !== 0 || last < first + 1)
    die('page range must be an odd first unmarked page followed by an even last marked page');
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(svar)) die('staged variable is not a JavaScript identifier: ' + svar);

  const rows = [];
  for (let source = first, n = 1; source < last; source += 2, n++) {
    const p = source + 1;
    const question = parseQuestion(ocrDir, source, n);
    const keypos = measureKey(pdf, p, question.opts.length);
    if (keypos.keyIndex !== null && (!Number.isInteger(keypos.keyIndex) || keypos.keyIndex < 0 || keypos.keyIndex >= question.opts.length))
      die('p.' + p + ': keypos returned invalid key index ' + keypos.keyIndex);
    rows.push({ n, p, key: keypos.keyIndex, stem: question.stem, opts: question.opts, expl: '', keypos,
      numberCheck: hasDigits(question) });
  }
  fs.writeFileSync(outFile, render(rows, svar, first, last), 'utf8');
  console.log(JSON.stringify(rows.map(row => ({ n: row.n, p: row.p, key: row.key, opts: row.opts.length,
    reason: row.keypos.reason, highlightPx: row.keypos.highlightPx, bodyBands: row.keypos.bodyBands,
    numberCheck: row.numberCheck })), null, 2));
}

main(process.argv.slice(2));
